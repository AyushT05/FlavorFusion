import { assets } from '@/Assets/assets'
import Image from 'next/image'
import React, { useState } from 'react'
import Link from 'next/link'
import BlogCard from './BlogCard'
import GetStarted from './GetStarted'
import { toast } from 'react-toastify'
import axios from 'axios'

const Header = () => {
  const [email,setEmail] = useState("");
  const onSubmitHandler = async (e) => {
    e.preventDefault();
    const formData = new FormData();
    formData.append("email" , email);
    const response = await axios.post('/api/email' , formData);
    if(response.data.success)
    {
      toast.success(response.data.message);
      setEmail("");
    }
    else{
      toast.error("Error");
    }

  }
  return (
    <div className='py-5 px-5 md:px-12 lg:px-26'>
        <div className='flex justify-between items-center'>
          <a href='http://localhost:5173/'>
            <Image src={assets.flavorfusion} width={220} alt='' className='w-[220px] sm:w-auto'/>
          </a> 
            <div className='flex items-center gap-2 font-medium py-1 px-3 sm:py-3 sm:px-6 '>
              <Link href='http://localhost:3008/admin/addProduct'><GetStarted/></Link>
            </div>
        </div>
        
        <div className='text-center my-8 relative rounded-lg overflow-hidden' style={{
            backgroundImage: `url('/latestpost1.jpg')`,
            backgroundSize: 'cover',
            backgroundRepeat: 'no-repeat',
            backgroundPosition: 'center',
            padding: '20px' // Optional padding for better spacing
          }}>
            {/* Dark overlay */}
            <div className='absolute inset-0 bg-black opacity-40 rounded-lg'></div>
            
            <h1 className='text-3xl sm:text-5xl font-medium relative z-10 text-white'>Latest Posts</h1>
            <p className='mt-10 max-w-[740px] m-auto text-xs sm:text-base relative z-10 text-white'>
              Each post in this section represents a unique recipe that has been generated by our AI, tailored to the specific ingredients and preferences shared by users. Whether you're seeking quick weeknight dinners or elaborate weekend feasts, our AI assistant helps transform available ingredients into delicious meals. Subscribe here to get access to the latest post at the earliest!
            </p>
        <form onSubmit={onSubmitHandler} className='flex justify-between max-w-[500px] scale-75 sm:scale-100 mx-auto mt-10 p-4 border border-black rounded-lg shadow-lg bg-white'>
          <input
            onChange={(e) => setEmail(e.target.value)}
            value={email}
            type="email"
            placeholder='Enter your email'
            className='flex-grow pl-4 py-2 outline-none border border-gray-300 rounded-l-lg focus:border-blue-500 transition duration-200'
          />
          <button className='border-1 border-black py-2 px-6 sm:px-8 rounded-r-lg bg-blue-500 text-white hover:bg-blue-600 active:bg-#ff333 transition duration-200'>
            Subscribe
          </button>
        </form>

        </div>
      
    </div>
  )
}

export default Header;
